let currentLanguage = null;

function languageFromNavigator() {
  const language = String(navigator.language || '').toLowerCase();
  if (language.startsWith('zh')) return 'zh';
  if (language.startsWith('en')) return 'en';
  return 'zh';
}

function getLanguage() {
  if (currentLanguage) return currentLanguage;
  let stored = null;
  try { stored = window.localStorage.getItem(I18N_STORAGE_KEY); } catch {}
  currentLanguage = stored === 'zh' || stored === 'en' ? stored : languageFromNavigator();
  return currentLanguage;
}

function interpolate(template, params = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => params[key] == null ? '' : String(params[key]));
}

function t(key, params = {}) {
  const value = I18N_MESSAGES[getLanguage()][key] || I18N_MESSAGES.en[key] || key;
  return interpolate(value, params);
}

function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
  root.querySelectorAll('[data-language-select]').forEach(el => { el.value = getLanguage(); });
  document.documentElement.lang = getLanguage() === 'zh' ? 'zh-CN' : 'en';
}

function setLanguage(language) {
  if (language !== 'zh' && language !== 'en') return;
  currentLanguage = language;
  try { window.localStorage.setItem(I18N_STORAGE_KEY, language); } catch {}
  applyTranslations();
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
}

function initLanguageSwitchers() {
  applyTranslations();
  document.querySelectorAll('[data-language-select]').forEach(select => {
    select.addEventListener('change', () => setLanguage(select.value));
  });
}

window.I18n = { t, getLanguage, setLanguage, applyTranslations };
window.t = t;
initLanguageSwitchers();
